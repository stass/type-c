module File = Typec_cpp.File
module Location = Typec_cpp.Location
module Reader = Typec_cpp.Reader
module Token = Typec_cpp.Token
module Tree = Typec_syntax.Tree

type name = { last_component : string }

(* A '"' or a newline would end the name in the redirect, and C leaves
   '\'' and '\\' undefined in a quoted header name (C11 6.4.7p3). *)
let is_name_byte = function
  | 'a' .. 'z' | 'A' .. 'Z' | '0' .. '9' | '.' | '_' | '-' | '+' -> true
  | _ -> false

let name_of_path path =
  let last_component = Filename.basename path in
  if
    Filename.check_suffix last_component File.interface_suffix
    && String.for_all is_name_byte last_component
  then Some { last_component }
  else None

(* The written form of a module (design 13.5): an ASCII letter or digit
   stands for itself, and every other byte is '_' and two hexadecimal
   digits, so every '_' begins an escape. *)
let module_name { last_component } =
  let module_name =
    Filename.chop_suffix last_component File.interface_suffix
  in
  let written = Buffer.create (String.length module_name) in
  let add = function
    | ('a' .. 'z' | 'A' .. 'Z' | '0' .. '9') as c -> Buffer.add_char written c
    | c -> Buffer.add_string written (Printf.sprintf "_%02x" (Char.code c))
  in
  String.iter add module_name;
  Buffer.contents written

let first_line = "/* Generated by typec --emit-c-header. Do not edit. */"

(* Raised at the first part of the interface that the header cannot
   carry, and caught once at each public entry. *)
exception Refused of Reader.error

let refuse location message = raise (Refused { Reader.location; message })

let catch_refusal f =
  match f () with
  | result -> Ok result
  | exception Refused error -> Error error

(* Checks of the step's output. *)

let empty_text_message =
  "the interface holds no token and no directive line in the output of \
   -E: it has no #ifndef guard of its own, which an interface that has a \
   header needs, or something defined that guard before the interface \
   was read, as a file that -include names does when it includes the \
   interface or defines its guard"

let inside_declaration_message (line : Reader.include_line) =
  Printf.sprintf
    "#%s %s inside a declaration of an interface whose header is \
     written: the header would hold the declaration without the text \
     that the line brings"
    line.directive line.header_name

(* An include line stands inside a declaration when the token after it
   is one of the declaration's but its first. *)
let check_include_place declarations (line : Reader.include_line) =
  let holds (span : Tree.span) =
    span.first < line.next_token && line.next_token <= span.last
  in
  if List.exists holds declarations then
    refuse line.location (inside_declaration_message line)

(* Lowering writes the guard of an instance, and -E writes no #ifndef or
   #endif line, so a guard line in the step's output is no text that the
   interface wrote. *)
let refuse_guard_line : Reader.guard_line -> unit = function
  | If_not_defined { location; _ } | End_if location ->
      refuse location
        "#ifndef or #endif line in the output of -E of an interface whose \
         header is written"

let check_interface ~source (read : Reader.interface) unit =
  catch_refusal (fun () ->
      if not read.holds_text then
        refuse
          { Location.file = source; line = 1; flags = No_flags }
          empty_text_message;
      let declarations =
        List.map Tree.external_span (Tree.external_declarations unit)
      in
      let check_part : Reader.own_part -> unit = function
        | Include_line line -> check_include_place declarations line
        | Guard_line line -> refuse_guard_line line
        | Own_token _ -> ()
      in
      List.iter check_part read.own_text)

(* Trigraphs (C11 5.2.1.1), which a client may compile with. *)

let is_trigraph_end = function
  | '=' | '(' | '/' | ')' | '\'' | '<' | '!' | '>' | '-' -> true
  | _ -> false

let holds_trigraph text =
  let is_trigraph_at index =
    text.[index] = '?'
    && text.[index + 1] = '?'
    && is_trigraph_end text.[index + 2]
  in
  let rec from index =
    index + 2 < String.length text
    && (is_trigraph_at index || from (index + 1))
  in
  from 0

(* An include line and a pragma line are written as the step wrote
   them, so a trigraph sequence in one would reach the client. *)
let refuse_trigraph location text =
  if holds_trigraph text then
    refuse location
      (Printf.sprintf
         "trigraph sequence in '%s', which a C client compiled with \
          trigraphs would replace"
         text)

(* A '\' between every two adjacent '?' of a literal leaves no two
   together, which escaping only the first pair of "???=" would not. *)
let escape_question_marks literal =
  let written = Buffer.create (String.length literal) in
  let add index c =
    if c = '?' && index > 0 && literal.[index - 1] = '?' then
      Buffer.add_char written '\\';
    Buffer.add_char written c
  in
  String.iteri add literal;
  Buffer.contents written

(* Include lines. *)

(* A client finds the header of another interface by the path through
   which the interface finds that interface. *)
let header_of_interface header_name =
  let length = String.length header_name in
  let enclosed = String.sub header_name 0 (length - 1) in
  let closing = header_name.[length - 1] in
  if Filename.check_suffix enclosed File.interface_suffix then
    Printf.sprintf "%s.h%c"
      (Filename.chop_suffix enclosed File.interface_suffix)
      closing
  else header_name

let include_line_text (line : Reader.include_line) =
  if line.directive = "include_next" then
    refuse line.location
      "#include_next in an interface whose header is written: a C client \
       would search on from the place of the header, not from that of \
       the interface";
  refuse_trigraph line.location
    (Printf.sprintf "#%s %s" line.directive line.header_name);
  Printf.sprintf "#%s %s" line.directive
    (header_of_interface line.header_name)

(* Runs. *)

(* A run as it is built: its lines, the tokens of its open line, and the
   identifiers of its tokens in the order in which they first appear. *)
type run = {
  mutable lines : string list;  (** in reverse *)
  mutable line : string list;  (** in reverse *)
  mutable line_location : Location.t option;
  mutable identifiers : string list;  (** in reverse *)
  seen : (string, unit) Hashtbl.t;
}

let new_run () =
  {
    lines = [];
    line = [];
    line_location = None;
    identifiers = [];
    seen = Hashtbl.create 64;
  }

(* No directive may define or undefine [defined] (C11 6.10.8p2), so it
   never names a macro, and GCC and Clang refuse its #undef. *)
let collect run name =
  if name <> "defined" && not (Hashtbl.mem run.seen name) then begin
    Hashtbl.add run.seen name ();
    run.identifiers <- name :: run.identifiers
  end

let close_line run =
  if run.line <> [] then
    run.lines <- String.concat " " (List.rev run.line) :: run.lines;
  run.line <- [];
  run.line_location <- None

(* The tokens of one line of the source share a line of the header, so
   that a client's diagnostics name a line that holds what the source's
   line did. The blank between two tokens keeps two '?' apart. *)
let add_to_line run (location : Location.t) text =
  let same_line (open_location : Location.t) =
    open_location.file = location.file && open_location.line = location.line
  in
  (match run.line_location with
  | Some open_location when same_line open_location -> ()
  | Some _ | None -> close_line run);
  run.line_location <- Some location;
  run.line <- text :: run.line

let add_whole_line run text =
  close_line run;
  run.lines <- text :: run.lines

(* The guard of an instance's or the trap's definition is a name of a
   run that the macro bracket does not name, so that it stays defined
   after the run (design 9.3); lowering writes no #define, which the
   reader would take for a macro's definition. *)
let add_guard_line run : Reader.guard_line -> unit = function
  | If_not_defined { name; _ } ->
      add_whole_line run ("#ifndef " ^ name);
      add_whole_line run ("#define " ^ name)
  | End_if _ -> add_whole_line run "#endif"

(* Compilers disagree on the spelling of an extended character that a
   pragma restores, so no spelling keeps every client's macro. *)
let is_basic_name name = String.for_all (fun c -> Char.code c < 0x80) name

let refuse_extended_identifier (token : Token.t) name =
  if not (is_basic_name name) then
    refuse token.location
    (Printf.sprintf
       "identifier '%s' with a character outside the basic character set \
        in an interface whose header is written: #pragma push_macro and \
        pop_macro restore no macro of it in every C client"
       name)

let add_token (lowered : Reader.t) run (token : Token.t) =
  let bytes = Reader.spelling lowered token in
  match token.kind with
  | Identifier name ->
      refuse_extended_identifier token name;
      collect run name;
      add_to_line run token.location name
  | Character _ | String _ ->
      add_to_line run token.location (escape_question_marks bytes)
  | Number | Punctuator _ -> add_to_line run token.location bytes
  | Pragma (Identifiers names) ->
      refuse_trigraph token.location bytes;
      List.iter (refuse_extended_identifier token) names;
      List.iter (collect run) names;
      add_whole_line run bytes
  | Pragma (Not_tokens _) ->
      invalid_arg "Header.add_token: Type-C text holds no such pragma"
  | Typec_pragma -> ()

(* The macro bracket (design 9.3): while the client reads the run, no
   identifier in it names a macro, and after it the client has every
   macro that it had. *)
let bracketed run =
  close_line run;
  let identifiers = List.rev run.identifiers in
  let push name =
    [ Printf.sprintf "#pragma push_macro(\"%s\")" name; "#undef " ^ name ]
  in
  let pop name = Printf.sprintf "#pragma pop_macro(\"%s\")" name in
  List.concat_map push identifiers
  @ List.rev run.lines
  @ List.map pop identifiers

(* The lines between the macro probe and the guard's #endif: the include
   lines, each where it stands, and the runs between them, each in its
   macro bracket. *)
let body (lowered : Reader.interface) =
  let written = ref [] in
  let run = ref (new_run ()) in
  let add lines = written := List.rev_append lines !written in
  let end_run () =
    add (bracketed !run);
    run := new_run ()
  in
  let write : Reader.own_part -> unit = function
    | Include_line line ->
        end_run ();
        add [ include_line_text line ]
    | Guard_line line -> add_guard_line !run line
    | Own_token token -> add_token lowered.unit !run token
  in
  List.iter write lowered.own_text;
  end_run ();
  List.rev !written

(* The macro bracket rests on #pragma push_macro and pop_macro, so the
   header fails to compile where they do not restore a macro: the
   #ifndef where conditionals are decided, the assertion where macros
   are replaced. *)
let macro_probe module_name =
  let probe = "__tc_macro_probe__" ^ module_name in
  [
    Printf.sprintf "#define %s 1" probe;
    Printf.sprintf "#pragma push_macro(\"%s\")" probe;
    "#undef " ^ probe;
    Printf.sprintf "#pragma pop_macro(\"%s\")" probe;
    "#ifndef " ^ probe;
    "#error \"this header needs #pragma push_macro and pop_macro\"";
    "#endif";
    Printf.sprintf "_Static_assert(%s, \"needs push_macro and pop_macro\");"
      probe;
    "#undef " ^ probe;
  ]

(* A Type-C unit reads the interface itself, and the redirect stands
   outside the guard, so no lowered text reaches it. *)
let write name lowered =
  catch_refusal (fun () ->
      let module_name = module_name name in
      let guard = "__tc_module__" ^ module_name in
      let skeleton_head =
        [
          first_line;
          "#ifdef __TYPEC__";
          Printf.sprintf "#include \"%s\"" name.last_component;
          "#else";
          "#ifndef " ^ guard;
          "#define " ^ guard;
        ]
      in
      let lines =
        skeleton_head @ macro_probe module_name @ body lowered
        @ [ "#endif"; "#endif" ]
      in
      String.concat "\n" lines ^ "\n")
